# /api/tests/test_rag_eval.py
"""
RAG quality evaluation with RAGAS.

This test is NOT a functional correctness test (test_rag_service.py and
test_integration.py already cover that) — it measures answer QUALITY
with objective RAGAS metrics:

- faithfulness: is the answer grounded only in the retrieved context,
  or is the LLM fabricating/hallucinating information?
- answer_relevancy: is the answer actually relevant to the question?
- context_precision (reference-free): are the retrieved chunks
  relevant, or just noise that confuses the LLM?

Serves as a quantitative check on RAGService's relevance-threshold fix
(see settings.min_relevance_score / _filter_by_relevance): the dataset
includes both questions within the test document's scope and questions
deliberately out of scope, to verify the latter trigger RAGService's
"I don't have that information" fallback instead of a fabricated answer.

Prerequisites (doesn't run in normal CI — only pytest -m unit does):
    ollama serve
    docker-compose up -d chromadb

Run with:
    pytest -m eval tests/test_rag_eval.py -v -s

v1: only reports scores (no threshold assertion) — there's no stable
baseline yet to compare against, and the metrics depend on a
non-deterministic local LLM. Results are saved to
eval_results/latest.json (gitignored) to compare manually between runs.
Check that file after changes to the prompt, min_relevance_score, or
the model.
"""

import json
import warnings
from pathlib import Path

import pytest

# ragas 0.4.x warns that ragas.metrics (the classic API, which is what we
# use here) will be deprecated in favor of ragas.metrics.collections
# (based on `instructor` instead of LangchainLLMWrapper) — see the
# comment in requirements.txt.
warnings.filterwarnings("ignore", category=DeprecationWarning)


# Questions derived directly from the content of data/test_document.pdf
# (generated by scripts/generate_test_pdf.py — deterministic, always the
# same text). The last two are deliberately unrelated to the document:
# they should trigger RAGService's fallback, not a made-up answer.
EVAL_DATASET = [
    {
        "question": "What does RAG stand for?",
        "ground_truth": "RAG stands for Retrieval-Augmented Generation, a technique that combines information retrieval with text generation via language models.",
        "in_scope": True,
    },
    {
        "question": "What language model does the system use?",
        "ground_truth": "The system uses Ollama with the llama3.2 model.",
        "in_scope": True,
    },
    {
        "question": "What vector database does the project use?",
        "ground_truth": "The project uses ChromaDB as its vector database.",
        "in_scope": True,
    },
    {
        "question": "What software architecture does the project use?",
        "ground_truth": "Hexagonal architecture (ports and adapters), to keep business logic independent from infrastructure.",
        "in_scope": True,
    },
    {
        "question": "What framework is used for the REST API?",
        "ground_truth": "FastAPI.",
        "in_scope": True,
    },
    {
        "question": "What advantages of the system are mentioned?",
        "ground_truth": "Full privacy (everything runs locally), no external API costs, scalable and maintainable, and easy to test.",
        "in_scope": True,
    },
    {
        "question": "What is the chemical formula of water?",
        "ground_truth": None,
        "in_scope": False,
    },
    {
        "question": "Who won the 2022 football World Cup?",
        "ground_truth": None,
        "in_scope": False,
    },
]

EVAL_COLLECTION = "bibliotecario_eval"  # dedicada, no toca bibliotecario_docs
EVAL_RESULTS_PATH = Path(__file__).parent / "eval_results" / "latest.json"


@pytest.mark.eval
@pytest.mark.integration
@pytest.mark.asyncio
async def test_rag_quality_with_ragas():
    """
    Ingests data/test_document.pdf into a dedicated collection, runs
    EVAL_DATASET through the real RAG pipeline, and computes RAGAS
    metrics over the resulting answers.
    """
    from app.adapters.outbound.ollama_adapter import OllamaAdapter
    from app.adapters.outbound.chromadb_adapter import ChromaDBAdapter
    from app.adapters.outbound.pdf_processor_adapter import PDFProcessorAdapter
    from app.core.services.sync_service import SyncService
    from app.core.services.rag_service import RAGService
    from app.core.domain.models import Query
    from app.config.settings import settings

    ollama = OllamaAdapter()
    if not await ollama.is_available():
        pytest.skip("Ollama is not available")

    chromadb = ChromaDBAdapter()
    try:
        await chromadb.collection_exists(EVAL_COLLECTION)
    except Exception:
        pytest.skip("ChromaDB is not available")

    test_pdf = Path(__file__).parent.parent.parent / "data" / "test_document.pdf"
    if not test_pdf.exists():
        pytest.skip(f"Test PDF not found at {test_pdf} (regenerate with scripts/generate_test_pdf.py)")

    # ========================================================================
    # STEP 1: Ingest the test document into a dedicated collection
    # ========================================================================
    pdf_processor = PDFProcessorAdapter()
    sync_service = SyncService(document_processor=pdf_processor, llm=ollama, vector_db=chromadb)
    sync_result = await sync_service.sync_document_from_file(str(test_pdf), collection_name=EVAL_COLLECTION)
    assert sync_result.success, f"Ingestion failed: {sync_result.message}"

    # ========================================================================
    # STEP 2: Run each question through the real RAG pipeline
    # ========================================================================
    rag_service = RAGService(llm=ollama, vector_db=chromadb)

    eval_rows = []
    for item in EVAL_DATASET:
        query = Query(question=item["question"], max_results=4)
        response = await rag_service.ask_question(query, collection_name=EVAL_COLLECTION)
        eval_rows.append({
            "question": item["question"],
            "ground_truth": item["ground_truth"],
            "in_scope": item["in_scope"],
            "answer": response.answer,
            "contexts": [doc.chunk_content for doc in response.source_documents],
        })

    # ========================================================================
    # STEP 3: Compute RAGAS metrics
    # ========================================================================
    from langchain_ollama import ChatOllama, OllamaEmbeddings
    from ragas import evaluate, EvaluationDataset
    from ragas.llms import LangchainLLMWrapper
    from ragas.embeddings import LangchainEmbeddingsWrapper
    from ragas.metrics import Faithfulness, ResponseRelevancy, LLMContextPrecisionWithoutReference

    # Judge: the same local Ollama, but through its own ChatOllama client
    # (RAGAS expects a LangChain BaseChatModel, not the completions-style
    # OllamaLLM the rest of the app uses) and temperature=0 to keep the
    # judgment as deterministic as possible.
    judge_llm = LangchainLLMWrapper(ChatOllama(
        model=settings.ollama_model,
        base_url=settings.ollama_base_url,
        temperature=0.0,
    ))
    judge_embeddings = LangchainEmbeddingsWrapper(OllamaEmbeddings(
        model=settings.ollama_embedding_model,
        base_url=settings.ollama_base_url,
    ))

    ragas_dataset = EvaluationDataset.from_list([
        {
            "user_input": row["question"],
            "response": row["answer"],
            "retrieved_contexts": row["contexts"] or ["(no context retrieved)"],
        }
        for row in eval_rows
    ])

    result = evaluate(
        dataset=ragas_dataset,
        metrics=[Faithfulness(), ResponseRelevancy(), LLMContextPrecisionWithoutReference()],
        llm=judge_llm,
        embeddings=judge_embeddings,
        raise_exceptions=False,  # a failed metric (e.g. NaN from the judge's invalid json) shouldn't fail the test
    )
    scores_df = result.to_pandas()

    # ========================================================================
    # STEP 4: Save and report results
    # ========================================================================
    EVAL_RESULTS_PATH.parent.mkdir(exist_ok=True)
    report = {
        "rows": [
            {
                **eval_rows[i],
                "faithfulness": _safe_float(scores_df.iloc[i].get("faithfulness")),
                "answer_relevancy": _safe_float(scores_df.iloc[i].get("answer_relevancy")),
                "context_precision": _safe_float(scores_df.iloc[i].get("llm_context_precision_without_reference")),
            }
            for i in range(len(eval_rows))
        ],
    }
    EVAL_RESULTS_PATH.write_text(json.dumps(report, ensure_ascii=False, indent=2))

    print("\n" + "=" * 100)
    print(f"{'Question':<45} {'Scope':<10} {'Faithful':<10} {'Relevancy':<10} {'CtxPrec':<10}")
    print("-" * 100)
    for row in report["rows"]:
        scope = "in-scope" if row["in_scope"] else "out-scope"
        print(
            f"{row['question'][:44]:<45} {scope:<10} "
            f"{_fmt(row['faithfulness']):<10} {_fmt(row['answer_relevancy']):<10} {_fmt(row['context_precision']):<10}"
        )
    print("=" * 100)
    print(f"Full results saved to: {EVAL_RESULTS_PATH}")

    # Success of the harness itself (not of RAG quality): that it ran
    # end to end and produced one row per question. Quality is read from
    # the report above / the JSON, not asserted here (see v1 note in the
    # module docstring).
    assert len(report["rows"]) == len(EVAL_DATASET)


def _safe_float(value) -> float | None:
    """None if the value is NaN (the judge failed to parse its own answer) or missing."""
    if value is None:
        return None
    try:
        f = float(value)
    except (TypeError, ValueError):
        return None
    return None if f != f else f  # f != f ⟺ NaN


def _fmt(value: float | None) -> str:
    return f"{value:.2f}" if value is not None else "N/A"
